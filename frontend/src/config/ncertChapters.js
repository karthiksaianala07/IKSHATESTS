/**
 * Retrieves the list of subtopics for a given subject and chapter.
 * If chapter is omitted or null, returns all unique subtopics for that subject.
 * Performs case-insensitive and partial key matching.
 */
export function getSubtopics(subject, chapter) {
  if (!subject) return [];
  const subMap = NCERT_SUBTOPICS[subject];
  if (!subMap) return [];

  if (!chapter || chapter === 'All' || chapter === 'All Chapters') {
    return Array.from(new Set(Object.values(subMap).flat()));
  }

  if (subMap[chapter]) {
    return subMap[chapter];
  }

  // Case-insensitive / trimmed lookup
  const normalizedCh = chapter.trim().toLowerCase();
  const foundKey = Object.keys(subMap).find(k => k.trim().toLowerCase() === normalizedCh);
  if (foundKey) return subMap[foundKey];

  // Partial substring matching
  const partialKey = Object.keys(subMap).find(k => 
    k.toLowerCase().includes(normalizedCh) || normalizedCh.includes(k.toLowerCase())
  );
  if (partialKey) return subMap[partialKey];

  return [];
}

